package com.coolcupman.dnasq.core

import java.security.SecureRandom
import kotlin.random.Random
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class DnaCoreTest {

    private val bases = "ACGT"

    /** Synthetic genome: rsid -> genotype. */
    private fun person(seed: Int, snps: Int = 20_000): Map<String, String> {
        val r = Random(seed)
        return (1..snps).associate { i ->
            "rs$i" to "${bases[r.nextInt(4)]}${bases[r.nextInt(4)]}"
        }
    }

    /** Same person, different lab run: some no-calls and genotyping errors. */
    private fun retest(p: Map<String, String>, seed: Int, errorRate: Double, noCallRate: Double) =
        Random(seed).let { r ->
            p.mapValues { (_, gt) ->
                when {
                    r.nextDouble() < noCallRate -> "--"
                    r.nextDouble() < errorRate -> "${bases[r.nextInt(4)]}${bases[r.nextInt(4)]}"
                    else -> gt
                }
            }
        }

    private fun as23andMe(p: Map<String, String>) = buildString {
        append("# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\n")
        p.entries.forEachIndexed { i, (rs, gt) -> append("$rs\t1\t${1000 + i}\t$gt\n") }
    }

    private fun asAncestry(p: Map<String, String>) = buildString {
        append("#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\n")
        p.entries.forEachIndexed { i, (rs, gt) ->
            val a = if (gt == "--") "00" else gt
            append("$rs\t1\t${1000 + i}\t${a[0]}\t${a[1]}\r\n")
        }
    }

    private fun enroll(text: String, lab: LabProfile = LabProfile.UNIVERSAL): DnaTemplate {
        val builder = DnaTemplate.Builder(lab, random = SecureRandom())
        GenotypeParser(lab).parse(text.reader().buffered(), builder::accept)
        return builder.build()
    }

    private fun verify(t: DnaTemplate, text: String, lab: LabProfile = LabProfile.UNIVERSAL): MatchResult {
        val v = t.verifier()
        GenotypeParser(lab).parse(text.reader().buffered(), v::accept)
        return v.result()
    }

    @Test
    fun sameLabRetestMatches() {
        val p = person(1)
        val t = enroll(as23andMe(p))
        val r = verify(t, as23andMe(retest(p, 2, errorRate = 0.005, noCallRate = 0.02)))
        assertTrue(r.matched, "$r")
        assertTrue(r.concordance > 0.98)
    }

    @Test
    fun crossLabRetestMatches() {
        val p = person(3)
        val t = enroll(as23andMe(p))
        // Different chip: only half the SNPs overlap, and reported on the opposite strand.
        val flipped = p.entries.filter { it.key.drop(2).toInt() % 2 == 0 }.associate { (k, v) ->
            k to v.map { mapOf('A' to 'T', 'T' to 'A', 'C' to 'G', 'G' to 'C')[it]!! }.joinToString("")
        }
        val r = verify(t, asAncestry(flipped))
        assertTrue(r.matched, "$r")
    }

    @Test
    fun differentPersonIsRejected() {
        val t = enroll(as23andMe(person(10)))
        repeat(5) { i ->
            val r = verify(t, as23andMe(person(100 + i)))
            assertFalse(r.matched, "$r")
            assertTrue(r.concordance < 0.6)
        }
    }

    @Test
    fun closeRelativeIsRejected() {
        val p = person(20)
        // Sibling-like: ~25% of calls differ.
        val sibling = retest(p, 21, errorRate = 0.33, noCallRate = 0.0)
        assertFalse(verify(enroll(as23andMe(p)), as23andMe(sibling)).matched)
    }

    @Test
    fun tooLittleOverlapIsRejected() {
        val p = person(30)
        val t = enroll(as23andMe(p))
        val tiny = p.entries.take(50).associate { it.key to it.value }
        assertFalse(verify(t, as23andMe(tiny)).matched)
    }

    @Test
    fun templateRoundTripsAndContainsNoGenotypes() {
        val p = person(40)
        val text = as23andMe(p)
        val t = enroll(text)
        val encoded = t.encode()
        val decoded = DnaTemplate.decode(encoded)
        assertEquals(t.panelSize, decoded.panelSize)
        assertContentEquals(encoded, decoded.encode())
        assertTrue(verify(decoded, text).matched)
        val ascii = String(encoded, Charsets.ISO_8859_1)
        assertFalse(ascii.contains("rs1"), "template must not contain rsIDs")
    }

    @Test
    fun templatesAreUnlinkable() {
        val text = as23andMe(person(50))
        val a = enroll(text).encode()
        val b = enroll(text).encode()
        // Fresh random key per enrollment -> no shared tags between two templates of the same person.
        val tagsA = a.drop(50).chunked(24).map { it.take(16) }.toSet()
        val tagsB = b.drop(50).chunked(24).map { it.take(16) }.toSet()
        assertTrue(tagsA.intersect(tagsB).isEmpty())
    }

    @Test
    fun parsesVcfAndCsv() {
        val vcf = """
            ##fileformat=VCFv4.2
            ##source=sequencer
            #CHROM	POS	ID	REF	ALT	QUAL	FILTER	INFO	FORMAT	SAMPLE
            chr1	100	rs1	A	G	50	PASS	.	GT:DP	0/1:30
            chr1	200	.	C	T	50	PASS	.	GT	1|1
            chr1	300	rs3	AT	A	50	PASS	.	GT	0/1
            chr1	400	rs4	G	A	50	LowQual	.	GT	0/1
            chr1	500	rs5	G	A,<NON_REF>	50	.	.	GT	./.
        """.trimIndent()
        val calls = mutableListOf<SnpCall>()
        val report = GenotypeParser(LabProfile.SEQUENCING).parse(vcf.reader().buffered()) { calls += it }
        assertEquals(DnaFileFormat.VCF, report.format)
        assertEquals(listOf("rs1" to "AG", "1:200" to "AA"), calls.map { it.locus to it.genotype })

        val csv = "RSID,CHROMOSOME,POSITION,RESULT\n\"rs9\",\"1\",\"5\",\"TC\"\n\"rs10\",\"X\",\"6\",\"--\"\n"
        calls.clear()
        GenotypeParser(LabProfile.MY_HERITAGE).parse(csv.reader().buffered()) { calls += it }
        assertEquals(listOf("rs9" to "AG"), calls.map { it.locus to it.genotype })
    }

    @Test
    fun labEditionRejectsOtherFormats() {
        assertFailsWith<DnaParseException> {
            GenotypeParser(LabProfile.ANCESTRY_DNA).parse(as23andMe(person(1, 10)).reader().buffered()) {}
        }
        assertFailsWith<DnaParseException> {
            GenotypeParser(LabProfile.UNIVERSAL).parse("hello world".reader().buffered()) {}
        }
    }

    @Test
    fun enrollmentNeedsEnoughCalls() {
        assertFailsWith<DnaParseException> { enroll(as23andMe(person(1, 100))) }
    }

    @Test
    fun normalizerIsStrandIndependent() {
        assertEquals(Normalizer.genotype("AG"), Normalizer.genotype("TC"))
        assertEquals(Normalizer.genotype("GA"), Normalizer.genotype("AG"))
        assertEquals(null, Normalizer.genotype("--"))
        assertEquals(null, Normalizer.genotype("DI"))
        assertEquals("X", Normalizer.chromosome("23"))
        assertEquals("MT", Normalizer.chromosome("chrM"))
    }

    @Test
    fun limiterBacksOffExponentially() {
        var now = 0L
        val limiter = AttemptLimiter { now }
        var s = AttemptLimiter.State()
        repeat(3) { s = limiter.onFailure(s); assertEquals(0, limiter.remainingLockMs(s)) }
        s = limiter.onFailure(s)
        assertEquals(30_000, limiter.remainingLockMs(s))
        s = limiter.onFailure(s)
        assertEquals(60_000, limiter.remainingLockMs(s))
        now += 60_000
        assertEquals(0, limiter.remainingLockMs(s))
        assertEquals(24 * 3600_000L, AttemptLimiter.lockoutFor(100))
    }
}
